// A team's agent.md: what the sessions it starts read before their first task. Two parts:
//   static   how a session works with agent-flow: written by agent-flow (rewritten when agent-flow changes it)
//   dynamic  the project context: kept by the team's manager (the session that hands out the tasks, or the router)
//            in context.md next to agent.md. When it changes, agent-flow puts the new text into agent.md and tells
//            the sessions that already read it (teams.ts, publishContext).
// Files in the team's folder: context.md (the manager edits it), agent.md (the sessions read it; on another machine a
// copy under the same place in that machine's ~/.agent-flow), context.published.md (the text agent.md has now).

import { join } from "node:path";

export const contextFiles = (teamDir: string) => ({
  dynamic: join(teamDir, "context.md"),
  agentMd: join(teamDir, "agent.md"),
  published: join(teamDir, "context.published.md"),
});

/** The same text, whatever the line endings and the blank lines at its ends. */
export const sameContext = (a: string, b: string) => a.replace(/\r\n/g, "\n").trim() === b.replace(/\r\n/g, "\n").trim();

/**
 * agent.md. mode: direct (sessions started with af task, which know nothing of agent-flow but this) or router (team
 * members, which were started with agent-flow's member instructions). af: the af command on the session's machine.
 */
export function agentMdText(mode: "direct" | "router", dynamic: string, af: string) {
  const who = mode === "direct" ? "the session that gives you tasks" : "the router of your team";
  const rules =
    mode === "direct"
      ? [
          "- Each task comes as a message that ends with its ticket number (T1, T2, …). When you finish it, end your reply",
          `  with a short summary of the result: agent-flow passes that reply on to ${who}.`,
          "- The user may also talk with you directly, here in your terminal. Just answer them: those answers are not passed",
          `  on. When that conversation changes something ${who} must know (progress on the work, or a change to what was`,
          `  agreed: scope, framing, decisions, numbers), tell it in one shell command: ${af} report "<what changed>".`,
          "  Not for answers to questions.",
        ]
      : ["- Work as your agent-flow member instructions say (af submit when you finish a ticket, af ask for a question)."];
  return [
    "# Your instructions from agent-flow",
    "",
    `agent-flow started you for ${who}. This file has two parts: how you work with agent-flow (written by agent-flow),`,
    `and the project context, kept by ${who}. Do not edit this file.`,
    "",
    "## How you work with agent-flow",
    "",
    ...rules,
    "- When the project context below changes, agent-flow tells you in a message. Read this file again then, and follow",
    "  the newer version from then on: it replaces the older one.",
    "",
    "## Project context",
    "",
    dynamic.trim() || "(None yet.)",
    "",
  ].join("\n");
}

/** What changed, line by line (a hint for the sessions; they read the whole part again). */
export function contextChanges(before: string, after: string, max = 1500) {
  const lines = (s: string) => s.replace(/\r\n/g, "\n").split("\n").map((l) => l.trimEnd()).filter((l) => l.trim());
  const a = lines(before);
  const b = lines(after);
  const had = new Set(a);
  const has = new Set(b);
  const out = [...a.filter((l) => !has.has(l)).map((l) => `- ${l}`), ...b.filter((l) => !had.has(l)).map((l) => `+ ${l}`)];
  let text = "";
  for (const l of out) {
    if (text.length + l.length + 1 > max) return `${text}… (more: read the file)`;
    text += `${l}\n`;
  }
  return text.trimEnd();
}
